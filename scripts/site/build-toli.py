MVS = "᠎"  # зайлуулагч — эцсийн ᠠ/ᠡ-г салангид сүүлээр бичнэ

# ᠮ ᠨ ᠶ ᠷ-ийн дараа эцсийн ᠠ ба ᠡ хоёул сална; ᠭ ᠬ-гийн дараа зөвхөн ᠠ сална.
# Хэмжсэн: ᠭ᠎ᠠ 1607/1612, ᠶ᠎ᠡ 78/79, ᠬ᠎ᠠ 152/155, ᠨ᠎ᠠ 159/170, ᠮ᠎ᠡ 82/85.
# Бусад гийгүүлэгчийн дараа (ᠲ ᠴ ᠵ ᠪ ᠳ ᠰ ᠫ ᠯ) нэг ч удаа салаагүй.
SEPARATES = {
    "ᠭ": {"ᠠ"},
    "ᠬ": {"ᠠ"},
    "ᠮ": {"ᠠ", "ᠡ"},
    "ᠨ": {"ᠠ", "ᠡ"},
    "ᠶ": {"ᠠ", "ᠡ"},
    "ᠷ": {"ᠠ", "ᠡ"},
}

# Толь эдгээрт эцсийн эгшгийг ЗАЛГАА бичдэг — дүрмийн жинхэнэ үл хамаарах
# зүйл. Их тайлбар толиос шалгав: энэ ᠡᠨᠡ, тэр ᠲᠡᠷᠡ, нар ᠨᠠᠷᠠ, ер ᠶᠡᠷᠡ,
# жар ᠵᠢᠷᠠ, найм ᠨᠠᠶᠮᠠ, ная ᠨᠠᠶᠠ. Бүгд төлөөний үг эсвэл тооны нэр —
# өдөр тутам хэрэглэгддэг тул уламжлалт бичлэгээ хадгалсан бололтой.
ATTACHED_FINAL = {"ene", "tere", "nara", "yere", "ǰira", "naima", "naya"}

VOWELS = set("ᠠᠡᠢᠣᠤᠥᠦᠧ")
DEMOTE = {"ᠣ": "ᠤ", "ᠥ": "ᠦ"}


def to_script(roman: str) -> str:
    out = ""
    index = 0
    seen_vowel = False
    while index < len(roman):
        for source, target in MAP:
            if roman.startswith(source, index):
                # ᠣ/ᠥ нь ЗӨВХӨН эхний үед орно; цаашид ᠤ/ᠦ болно —
                # mongγol → ᠮᠣᠩᠭᠤᠯ, orqon → ᠣᠷᠬᠤᠨ. Толь энэ жишгийг
                # 99.2% баримталдаг.
                if seen_vowel:
                    target = "".join(DEMOTE.get(char, char) for char in target)
                if not seen_vowel and any(char in VOWELS for char in target):
                    seen_vowel = True
                out += target
                index += len(source)
                break
        else:
            raise ValueError(f"тодорхойгүй үсэг: {roman[index]!r} ({roman})")

    # Эцсийн ᠠ/ᠡ салах эсэх — өмнөх гийгүүлэгч ба эгшиг хоёул шийднэ.
    last = out[-1:]
    previous = out[-2:-1]
    if (
        roman not in ATTACHED_FINAL
        and last in ("ᠠ", "ᠡ")
        and last in SEPARATES.get(previous, ())
    ):
        out = out[:-1] + MVS + last

    return out


