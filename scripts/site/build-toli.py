# Багш нягталж баталсан үгс. Энд нэмсэн үг сайт дээр «нягталсан» болно.
VERIFIED = set()

CYRILLIC_ORDER = "абвгдеёжзийклмноөпрстуүфхцчшщъыьэюя"


def sort_key(entry):
    return [CYRILLIC_ORDER.index(c) if c in CYRILLIC_ORDER else 99 for c in entry[0]]


def main() -> None:
    seen = set()
    for cyrillic, _ in STEMS:
        if cyrillic in seen:
            raise ValueError(f"давхардсан язгуур: {cyrillic}")
        seen.add(cyrillic)

    rows = sorted(STEMS, key=sort_key)
    lines = [f'  {c}: "{to_script(r)}", // {r}\n' for c, r in rows]

    # --- 1. TS толь ---------------------------------------------------------
    path = "src/lib/mongolScript.ts"
    source = io.open(path, encoding="utf-8").read()
    start = source.index("const STEMS: Record<string, string> = {")
    end = source.index("};", start) + 2
    block = (
        "const STEMS: Record<string, string> = {\n"
        + "".join(lines)
        + "};"
    )
    io.open(path, "w", encoding="utf-8").write(source[:start] + block + source[end:])

    # --- 2. Багшид зориулсан хяналтын хуудас --------------------------------
    doc = ["""# Нэрийн язгуурын толь

`src/lib/mongolScript.ts` дахь толийн бүрэн жагсаалт. Сайт нэрийг хөрвүүлэхдээ
эхлээд эндээс хайж, олдвол **сонгодог бичлэгээр** буулгадаг; олдохгүй бол
дуудлагаар нь буулгана.

Багш нягталж, буруу байвал `scripts/build-toli.py` доторх **романчлалыг**
засаад `python scripts/build-toli.py` ажиллуулна — Unicode нь өөрөө шинэчлэгдэнэ.
Гараар TS файл засах шаардлагагүй.

Төвдөөс орсон нэрс (Балдан, Гончиг, Дамдин, Жигжид, Нацаг, Рэнцэн, Чойжил,
Лхам, Аюуш, Бадам) хамгийн их эргэлзээтэй — эдгээрийг түрүүлж нягтлахыг зөвлөе.

| Кирилл | Монгол бичиг | Романчлал |
| --- | --- | --- |
"""]
    for cyrillic, roman in rows:
        doc.append(f"| {cyrillic} | {to_script(roman)} | {roman} |\n")
    doc.append(f"\nНийт **{len(rows)}** язгуур.\n")
    io.open("docs/toli.md", "w", encoding="utf-8").write("".join(doc))

    print(f"{len(rows)} stems written -> src/lib/mongolScript.ts, docs/toli.md")
    build_words()


def build_words() -> None:
    """Албан бичгийн үгсийн санг TS толь ба хяналтын хуудас болгож бичнэ."""
    seen = set()
    for cyrillic, _ in WORDS:
        if cyrillic in seen:
            raise ValueError(f"давхардсан үг: {cyrillic}")
        seen.add(cyrillic)

    for word in VERIFIED:
        if word not in seen:
            raise ValueError(f"VERIFIED дотор толинд байхгүй үг: {word}")

    rows = sorted(WORDS, key=sort_key)

    # --- 1. TS толь ---------------------------------------------------------
    header = '''/**
 * Урсгал бичвэрийн үгсийн сан — `scripts/build-toli.py` үүсгэсэн.
 * **Гараар бүү зас**: романчлалыг нь скрипт дотор засаад
 * `python scripts/build-toli.py` ажиллуулна.
 *
 * `WORDS` нь **язгуур** хадгална — нөхцөлийг `mongolText.ts` тусад нь салгаж,
 * монгол бичгийн дүрмээр залгана.
 *
 * `VERIFIED` нь багш нүдээр нягталсан үгс. Бусад нь ноорог: уншигдана, гэхдээ
 * сонгодог бичлэг байх баталгаагүй тул сайт дээр тусад нь тэмдэглэгдэнэ.
 */

'''

    ts = [header, "export const WORDS: Record<string, string> = {\n"]
    ts += ['  %s: "%s", // %s\n' % (c, to_script(r), r) for c, r in rows]
    ts.append("};\n\n")
    ts.append("/** Багш нягталсан үгс — сайт дээр «нягталсан» гэж тэмдэглэгдэнэ */\n")
    ts.append("export const VERIFIED: ReadonlySet<string> = new Set([\n")
    ts += ['  "%s",\n' % w for w in sorted(VERIFIED, key=lambda w: sort_key((w, "")))]
    ts.append("]);\n")

    io.open(
        "src/lib/mongolLexicon.ts", "w", encoding="utf-8", newline="\n"
    ).write("".join(ts))

    # --- 2. Багшид зориулсан хяналтын хуудас --------------------------------
    doc = ["""# Албан бичгийн үгсийн сан

`src/lib/mongolLexicon.ts` дахь толийн бүрэн жагсаалт. Урсгал бичвэр хөрвүүлэхэд
сайт үгийн **нөхцөлийг салгаад** язгуурыг нь эндээс хайна (улс|ын → ᠤᠯᠤᠰ ᠤᠨ).

Бичлэгийг засах: `scripts/build-toli.py` доторх `WORDS` жагсаалтын
**романчлалыг** засаад `python scripts/build-toli.py` ажиллуулна. TS файлыг
гараар засах хэрэггүй.

«Нягталсан» багана нь багш баталсан эсэхийг заана. Баталсан үгээ скриптийн
`VERIFIED` олонлогт нэмбэл сайт дээр итгэлтэй өнгөөр гарна. Одоогоор бүх бичлэг
ноорог — хамгийн олон давтагддаг үгсийг нь түрүүлж нягтлахыг зөвлөе.

| Кирилл | Монгол бичиг | Романчлал | Нягталсан |
| --- | --- | --- | --- |
"""]
    for cyrillic, roman in rows:
        mark = "✅" if cyrillic in VERIFIED else "—"
        doc.append(f"| {cyrillic} | {to_script(roman)} | {roman} | {mark} |\n")
    doc.append(
        f"\nНийт **{len(rows)}** үг, үүнээс **{len(VERIFIED)}** нь нягталсан.\n"
    )
    io.open("docs/toli-ug.md", "w", encoding="utf-8", newline="\n").write("".join(doc))

    print(f"{len(rows)} words written -> src/lib/mongolLexicon.ts, docs/toli-ug.md")


