/**
 * НЭРИЙН ТОЛЬ — хоёр эх сурвалжийн нийлбэр.
 *
 * Монгол нэр бараг үргэлж ердийн үгийн нийлбэр байдаг (Мөнх+цэцэг, Ган+болд)
 * тул нэрийг задлаад хэсэг тус бүрийг толиос хайх нь хамгийн үр дүнтэй.
 * Хоёр толь бие биеэ нөхнө — 88 нэр дээр хэмжихэд:
 *
 *   `STEMS` дангаараа                77
 *   Их тайлбар толь дангаараа        74
 *   ХОЁУЛАА                          87
 *
 * Учир нь тэдгээр өөр өөр зүйл мэддэг. Их тайлбар толь бол ҮГИЙН толь —
 * «саран», «ууган», «билгүүн», «анужин» мэт ердийн үгийг мэднэ, харин
 * «дорж», «дулмаа», «гомбо», «цэрэн» мэт төвд гаралтай нэр, «-маа» дагавар
 * тэнд толгой үгээр байхгүй. `STEMS` яг тэднийг барина.
 *
 * ⚠ ЗӨРВӨЛ НЭРИЙН ТОЛЬ ЯЛНА. Нэрийн зөв бичих зүй нь ердийн үгийнхээс
 * ТУСДАА: «даваа» гэдэг үг ᠳᠠᠪᠠᠭ᠎ᠠ (уул давах) ч, ижил дуудлагатай НЭР нь
 * ᠳᠠᠸᠠ (төвд «zla ba» — гараг). Ийм тохиолдол ганц биш: `STEMS`-ийн 234
 * үгийн 207 нь толинд бий, тэдгээрийн 33 нь зөрдөг — «түвшин» толинд
 * ᠲᠥᠪᠰᠢᠨ, «мөнгөн» ᠮᠣᠢᠩᠭᠥᠨ, «хатан» ᠬᠠᠲᠠᠨ, «одон» ᠤᠳᠦᠨ.
 *
 * Тиймээс энэ хүснэгт нь ердөө «нөөц» биш, НЭРИЙН эрх мэдэлтэй эх сурвалж:
 * язгуур энд байвал толийг харахгүй. Их тайлбар толь нь `STEMS`-д БАЙХГҮЙ
 * язгуурыг («саран», «ууган», «билгүүн», «анужин») нөхөх үүрэгтэй.
 *
 * Үүний хариуцлага нь: **буруу нэр гарвал засвар нь энэ хүснэгтэд ордог.**
 * Гар хийцийн 234 мөр тул алдаа байж болно — толь эсрэгээрээ бичсэн язгуур
 * бүрийг `scripts/measure-rules.mts`-ийн хажууд шалгаж болно.
 *
 * `NameToli` нь толийн БҮХ хувилбарыг эрэмбэтэйгээр («/api/toli»-гийн
 * `found` + `variants`) хүлээж авна — омоним үгэнд үндсэн утга нь нэрийнх
 * байх албагүй тул сонголт үлдээх шаардлагатай.
 */
export type NameToli = Record<string, string[]>;

/**
 * Толиос асуух нэр дэвшигчид: нэрийн бүх гурав ба түүнээс дээш үсэгт хэсэг.
 * `/api/toli` нэг хүсэлтэд 500 үг авдаг тул тэр хязгаарт нь тааруулж таслав.
 *
 * Яагаад бүх хэсгийг вэ: аль нь язгуур болохыг УРЬДЧИЛАН мэдэхгүй. «саран»
 * язгуур гэдгийг зөвхөн толь хариулсны дараа мэднэ — тэр болтол «сар»+«ан»
 * гэж буруу таслах эрсдэлтэй.
 */
export function nameLookups(input: string): string[] {
  const out = new Set<string>();

  for (const word of nameWords(input)) {
    const forms = CYRILLIC_RE.test(word) ? [word] : [latinToCyrillic(word)];

    for (const form of forms) {
      if (!form) continue;
      for (let start = 0; start < form.length; start += 1) {
        for (let end = form.length; end - start >= 3; end -= 1) {
          out.add(form.slice(start, end));
        }
      }
    }
  }

  return [...out].slice(0, 500);
}

function nameWords(input: string): string[] {
  return input
    .trim()
    .toLowerCase()
    .split(/[\s.,]+/)
    .filter(Boolean)
    .slice(0, 4);
}

const CYRILLIC_RE = /[Ѐ-ӿ]/;

type WordResult = { text: string; matched: number; length: number };

type Part = { cyr: string; script: string };

/**
 * Нэг язгуурыг хоёр толиос хайна. Гурваас богино хэсгийг ЗӨВХӨН `STEMS`-ээс
 * зөвшөөрнө: Их тайлбар толинд «а», «о» гэх мэт үсгийн нэр толгой үгээр
 * бүртгэгдсэн байдаг тул тэднийг язгуур гэж үзвэл нэр хэлтэрхий болно.
 *
 * Нэрийн толь эхэнд — дээрх `NameToli`-гийн тайлбарыг үз. Толь нь `STEMS`-д
 * БАЙХГҮЙ язгуурыг нөхөх үүрэгтэй.
 *
 * Толиос ирсэн бичлэгийг `matchFirstRounded`-оор нэг шүүнэ: толинд «түвшин»
 * нь ᠲᠥᠪᠰᠢᠨ гэж, өөрөөр хэлбэл «төвшин» гэсэн кирилл хувилбарын бичлэгээр
 * бүртгэгдсэн байдаг.
 */
function lookupNameStem(cyr: string, toli?: NameToli): Part | null {
  const fromStems = STEMS[cyr];
  if (fromStems) return { cyr, script: fromStems };

  const fromToli = toli?.[cyr]?.[0];
  if (fromToli && cyr.length >= 3) {
    return { cyr, script: matchFirstRounded(cyr, fromToli) };
  }
  return null;
}

/**
 * Нэрийг БҮХЭЛД нь мэдэгдэх язгуурт задлана. Задрал бүрэн байх ёстой —
 * нэг ч үсэг гадуур үлдвэл энэ зам бүтэлгүйтэж, доорх дуудлагатай холимог
 * зам ажиллана.
 *
 * Сонголтын дараалал: хэсэг цөөтэй нь эхэлж (нэр ихэвчлэн хоёр язгуур),
 * тэнцвэл хамгийн богино хэсэг нь урт байгаа нь. Ингэснээр «сарангэрэл» нь
 * «сар|ан|гэрэл» биш «саран|гэрэл» гэж задарна.
 */
function decompose(word: string, toli?: NameToli): Part[] | null {
  const memo = new Map<number, Part[] | null>();

  const solve = (from: number): Part[] | null => {
    if (from === word.length) return [];
    const cached = memo.get(from);
    if (cached !== undefined) return cached;

    let best: Part[] | null = null;

    for (let end = word.length; end > from; end -= 1) {
      const part = lookupNameStem(word.slice(from, end), toli);
      if (!part) continue;

      const tail = solve(end);
      if (!tail) continue;

      const candidate = [part, ...tail];
      if (!best || betterSplit(candidate, best)) best = candidate;
    }

    memo.set(from, best);
    return best;
  };

  return solve(0);
}

function betterSplit(a: Part[], b: Part[]): boolean {
  if (a.length !== b.length) return a.length < b.length;
  return shortestPart(a) > shortestPart(b);
}

function shortestPart(parts: Part[]): number {
  return Math.min(...parts.map((part) => part.cyr.length));
}

/**
 * Кирилл үгийг толь ба дуудлага хоёрын аль болох сайн хослолоор буулгана.
 *
 * Эхлээд БҮРЭН задрал хайна — бүх хэсэг нь толинд байвал үр дүн нь жинхэнэ
 * сонгодог бичлэг болно. Олдохгүй бол эхнээс нь шунахайран уншиж, таарсныг
 * толиор, таараагүй завсрыг дуудлагаар буулгана: «Батжав» → ᠪᠠᠲᠤ (толь) +
 * ᠵᠠᠪ (дуудлага).
 */
function convertCyrillicWord(word: string, toli?: NameToli): WordResult {
  const whole = decompose(word, toli);

  if (whole) {
    return {
      text: joinScript(whole.map((part) => part.script)),
      matched: word.length,
      length: word.length,
    };
  }

  const front = isFrontWord(word);
  let rest = word;
  const pieces: string[] = [];
  let matched = 0;

  while (rest.length > 0) {
    const stem = longestStemAt(rest, 0, toli);

    if (stem) {
      pieces.push(stem.script);
      matched += stem.cyr.length;
      rest = rest.slice(stem.cyr.length);
      continue;
    }

    // Дараагийн язгуур хаанаас эхлэхийг хайж, хоорондох хэсгийг дуудлагаар.
    let next = rest.length;
    for (let index = 1; index < rest.length; index += 1) {
      if (longestStemAt(rest, index, toli)) {
        next = index;
        break;
      }
    }

    pieces.push(cyrillicPhonetic(rest.slice(0, next), front));
    rest = rest.slice(next);
  }

  return { text: joinScript(pieces), matched, length: word.length };
}

/** Өгөгдсөн байрлалаас эхлэх ХАМГИЙН УРТ мэдэгдэх язгуур */
function longestStemAt(
  word: string,
  from: number,
  toli?: NameToli,
): Part | null {
  for (let end = word.length; end > from; end -= 1) {
    const part = lookupNameStem(word.slice(from, end), toli);
    if (part) return part;
  }
  return null;
}

/**
 * Латинаар бичсэн монгол нэрийг таних оролдлого: Ganbold → ганболд → толь.
 * Таарахгүй бол хоосон буцаана — гадаад нэр байсан гэсэн үг.
 */
const LATIN_TO_CYRILLIC: Record<string, string> = {
  kh: "х",
  ch: "ч",
  sh: "ш",
  ts: "ц",
  ya: "я",
  yo: "ё",
  yu: "ю",
  uu: "уу",
  oo: "оо",
  aa: "аа",
  ee: "ээ",
  a: "а",
  b: "б",
  c: "ц",
  d: "д",
  e: "э",
  f: "ф",
  g: "г",
  h: "х",
  i: "и",
  j: "ж",
  k: "к",
  l: "л",
  m: "м",
  n: "н",
  o: "о",
  p: "п",
  q: "х",
  r: "р",
  s: "с",
  t: "т",
  u: "у",
  v: "в",
  w: "в",
  x: "кс",
  y: "й",
  z: "з",
};

function latinToCyrillic(word: string): string {
  let out = "";
  let index = 0;

  while (index < word.length) {
    const pair = word.slice(index, index + 2);
    if (LATIN_TO_CYRILLIC[pair]) {
      out += LATIN_TO_CYRILLIC[pair];
      index += 2;
      continue;
    }

    out += LATIN_TO_CYRILLIC[word[index]] ?? "";
    index += 1;
  }

  return out;
}

/**
 * Нэрийг монгол бичигт хөрвүүлнэ. Үг бүр тусдаа багана болно —
 * босоо бичигт багана нь зүүнээс баруун тийш дараалдаг.
 *
 * `toli` нь Их тайлбар толиос татсан язгуурууд — `nameLookups()`-оор асууж
 * аваад энд өгнө. Өгөхгүй бол багцад суусан `STEMS` дангаараа ажиллана:
 * сүлжээгүй үед ч, толийн хариу ирэхээс өмнөх эхний зурагт ч үр дүн гарна.
 */
export function convertName(input: string, toli?: NameToli): ConvertedName {
  const words = nameWords(input);

  if (words.length === 0) {
    return { words: [], text: "", source: "empty" };
  }

  let matched = 0;
  let total = 0;

  const converted = words.map((word) => {
    if (CYRILLIC_RE.test(word)) {
      const result = convertCyrillicWord(word, toli);
      matched += result.matched;
      total += result.length;
      return result.text;
    }

    // Латинаар бичсэн монгол нэр байж магадгүй — эхлээд толиос хайна.
    const asCyrillic = latinToCyrillic(word);
    const guess = asCyrillic ? convertCyrillicWord(asCyrillic, toli) : null;

    if (guess && guess.matched === guess.length && guess.text) {
      matched += guess.length;
      total += guess.length;
      return guess.text;
    }

    total += word.length;
    return latinPhonetic(word);
  });

  // Эм ᠭ/ᠬ-г тусдаа кодоор гаргах нь ХАМГИЙН СҮҮЛИЙН алхам — толь, хүснэгт,
  // залгалт бүгд жирийн ᠭ/ᠬ-тэй ажилласны дараа.
  const clean = converted.filter(Boolean).map(applyFeminineVelars);

  const source: ConvertSource =
    matched === total ? "dictionary" : matched > 0 ? "mixed" : "phonetic";

  return { words: clean, text: clean.join(" "), source };
}
