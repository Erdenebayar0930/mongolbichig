/** Уртаас богино руу — «алтан» нь «алт»-аас түрүүнд таарах ёстой */
const STEM_KEYS = Object.keys(STEMS).sort((a, b) => b.length - a.length);

/**
 * ЭГШГИЙН ЗОХИЦОЛ — монгол бичгийн үндсэн дүрэм.
 *
 * Монгол үг эр (а, о, у), эм (э, ө, ү) хоёрын аль нэгэнд бүхэлдээ харьяалагдана;
 * «и» бол саармаг — аль ч зэрэгт орж чадна. Зэргийг үгийн ЭХНИЙ саармаг бус
 * эгшгээр тодорхойлно.
 *
 * ⚠ Өмнө нь «и», «е» хоёрыг эм эгшигт тооцож, үгийн ХААНААС Ч ОЛДВОЛ эм гэж
 * үздэг байсан. Тэгснээр «ажиллах», «аймаг», «сайхан» мэт эр үгс эм болж
 * ангилагдаж, эцсийн «х» нь ᠬᠦ, нөхцөл нь ᠦᠨ болж буруу гарч байв.
 */
export type Harmony = "back" | "front" | "neutral";

/** Эр эгшиг. «я» = ᠶᠠ, «ё» = ᠶᠣ тул тэдгээр нь ч эр эгшиг агуулна. */
const BACK_VOWELS = new Set(["а", "о", "у", "я", "ё"]);

/** Эм эгшиг */
const FRONT_VOWELS = new Set(["э", "ө", "ү"]);

/** Үгийн эгшгийн зэргийг тодорхойлно — эхний саармаг бус эгшиг шийднэ. */
export function wordHarmony(word: string): Harmony {
  for (const char of word) {
    if (BACK_VOWELS.has(char)) return "back";
    if (FRONT_VOWELS.has(char)) return "front";
  }
  return "neutral";
}

/**
 * Эм зэрэгт тооцох эсэх. Зөвхөн «и»-тэй үг (бичиг, түшиг, чимэг) уламжлалаар
 * эм зэрэгт ордог — толин дээр хэмжихэд «и»-ээс өөр эгшиггүй, «х»-ээр төгссөн
 * 134 үгийн 107 нь ᠬᠦ авсан.
 */
export function isFrontWord(word: string) {
  return wordHarmony(word) !== "back";
}

/**
 * Үгийн ЭЦСИЙН эгшгийн зэрэг. Нийлмэл үгийн эхний ба сүүлийн хэсэг өөр
 * зэрэгтэй байж болно («ааг|гүй|дэх» — эхэндээ эр, сүүлдээ эм). Эцэст нь
 * залгах эгшгийг хамгийн ойрын, өөрөөр хэлбэл СҮҮЛИЙН эгшиг шийднэ: толин
 * дээр «-х»-ийн 267 зөрүү бүгд ийм нийлмэл үг байв.
 */
function endingHarmony(word: string): Harmony {
  for (let index = word.length - 1; index >= 0; index -= 1) {
    if (BACK_VOWELS.has(word[index])) return "back";
    if (FRONT_VOWELS.has(word[index])) return "front";
  }
  return "neutral";
}

