/**
 * Кирилл үгийг дуудлагаар нь монгол бичигт буулгана.
 *
 * `wordFront` нь эр/эм зэргийг гаднаас өгнө: язгуур таслаад үлдсэн хэсгийг
 * дангаар нь буулгах үед («оюун|чимэг») зэргийг нь бүтэн үгээр тодорхойлох
 * ёстой, эс бөгөөс хэсэг бүр өөр өөрийн зэрэгтэй болно.
 */
export function cyrillicPhonetic(word: string, wordFront?: boolean): string {
  const front = wordFront ?? isFrontWord(word);
  // Эцсийн гийгүүлэгчид залгах эгшгийг сүүлийн эгшиг шийднэ (дээрх тайлбар).
  const finalFront = wordFront ?? endingHarmony(word) !== "back";
  let out = "";
  let index = 0;

  /**
   * ᠣ/ᠥ нь зөвхөн ЭХНИЙ үед орно (`rounded-position` дүрэм). Тиймээс эхний
   * эгшгээ гаргасны дараа гарах бүх ᠣ/ᠥ-г ᠤ/ᠦ болгоно — «монгол» нь
   * ᠮᠣᠩᠭᠣᠯ биш ᠮᠣᠩᠭᠤᠯ, «орон» нь ᠣᠷᠣᠨ биш ᠣᠷᠤᠨ.
   *
   * Хүснэгтүүдэд эхний үеийн хэлбэрээр нь (ᠣ, ᠥ) бичсэн бөгөөд бууруулалт
   * зөвхөн энд болно. Ингэснээр дүрэм НЭГ газар сууна.
   */
  let seenVowel = false;

  function emit(chunk: string) {
    for (const char of chunk) {
      const next = seenVowel ? demoteRounded(char) : char;

      // ᠠᠠ, ᠡᠡ дараалал сонгодог бичигт БАЙХГҮЙ (54916 үгэнд 0 удаа) — дунд нь
      // ᠭ ордог. Хүснэгтүүд урт эгшгийг өөрсдөө барьдаг ч хоёр хэсэг залгах
      // үед давхарлаж болзошгүй: «ааяа» → ᠠᠭᠠ + ᠶᠠ + ᠠ. Энд барина.
      if ((next === "ᠠ" || next === "ᠡ") && out.slice(-1) === next) out += "ᠭ";

      out += next;
      if (SCRIPT_VOWELS.has(char)) seenVowel = true;
    }
  }

  while (index < word.length) {
    const pair = word.slice(index, index + 2);
    const atEnd = index + 2 === word.length;

    if (LONG_VOWELS[pair]) {
      emit((atEnd ? FINAL_LONG_VOWELS : LONG_VOWELS)[pair]);
      index += 2;
      continue;
    }

    // ⚠ Үгийн эцсийн гийгүүлэгч хосын ХОЁР ДАХЬ гишүүн байвал хосыг барихгүй.
    // «анх» → «нх» хос нь ᠠᠩᠬ гэж эгшиггүй төгсөж, `bare-final-consonant`
    // дүрмийг зөрчиж байв. Хосыг тайлбал «н» → ᠩ, «х» → ᠬᠤ болж ᠠᠩᠬᠤ гарна.
    if (CYRILLIC_PAIRS[pair] && !(atEnd && FINAL_CONSONANTS[pair[1]])) {
      emit(CYRILLIC_PAIRS[pair]);
      index += 2;
      continue;
    }

    const char = word[index];
    const last = index === word.length - 1;

    // Үгийн эцсийн гийгүүлэгч — эр/эм зэргээрээ эгшгээ авна.
    if (last && FINAL_CONSONANTS[char]) {
      emit(FINAL_CONSONANTS[char][finalFront ? "front" : "back"]);
      index += 1;
      continue;
    }

    // «н» нь ᠭ ᠬ болон ш, с-ийн өмнө ᠩ болно: унших → ᠤᠩᠰᠢᠬᠤ, анх → ᠠᠩᠬᠤ.
    // Дараагийн үсгийг зарцуулахгүй — түүнийг дараагийн эргэлт барина.
    if (char === "н" && NGA_BEFORE.has(word[index + 1])) {
      emit("ᠩ");
      index += 1;
      continue;
    }

    // «т» нь гийгүүлэгчийн өмнө ᠳ болно (`ta-before-consonant` дүрэм).
    // Уугуул үгэнд гийгүүлэгчийн өмнө ᠳ 1044, ᠲ ердөө 6 удаа таарсан.
    if (char === "т" && !last && CONSONANTS.has(word[index + 1])) {
      emit("ᠳ");
      index += 1;
      continue;
    }

    if (char === "ю") {
      emit(front ? "ᠶᠦ" : "ᠶᠤ");
      index += 1;
      continue;
    }

    // «е» нь үгийн эхэнд л ᠶᠡ (ер → ᠶᠡᠷᠡ); гийгүүлэгчийн ард зүгээр ᠡ
    // (сервер → ᠰᠡᠷᠸᠡᠷ). Толинд «е»-тэй 1020 үгийн 994 нь ᠶᠡ-гүй байв.
    if (char === "е" && index > 0) {
      emit("ᠡ");
      index += 1;
      continue;
    }

    emit(CYRILLIC[char] ?? "");
    index += 1;
  }

  return separateFinalVowel(out);
}

/** Кирилл гийгүүлэгч — «т» нь ᠳ болох эсэхийг шийдэхэд */
const CONSONANTS = new Set("бвгджзйклмнпрстфхцчшщ");

/** «н» нь эдгээрийн өмнө ᠩ болно (`nga-before-velar` дүрэм, ш/с нь дуудлага) */
const NGA_BEFORE = new Set("гхкшс");

/**
 * Үгийн эцсийн ᠠ/ᠡ-г дүрмийн хүснэгтээр салгана. Энэ НЭГ мөр нь «дараа» →
 * ᠳᠠᠷᠠᠭ᠎ᠠ (ᠭ-ийн ард ᠠ сална) ба «хот» → ᠬᠣᠲᠠ (ᠲ-ийн ард залгана) хоёрыг
 * зэрэг шийднэ — өмнө нь урт эгшгийн хүснэгтэд гараар бичигдсэн зайлуулагч
 * зөвхөн «аа», «оо»-г барьдаг байсан бөгөөд эцсийн гийгүүлэгчийн эгшгийг
 * огт хамардаггүй байв.
 */
/**
 * Нэрийн хэсгүүдийг ЗАЛГАХАД дүрэм үйлчилнэ — зүгээр `join("")` хийж болохгүй.
 *
 * Хоёр зүйл эвдэрдэг:
 *
 *   1. **Зайлуулагч дунд үлдэнэ.** «бадам» нь дангаараа ᠪᠠᠳᠮ᠎ᠠ (эцсийн ᠠ
 *      сална) ч «Бадамцэцэг» дотор тэр ᠠ нь үгийн эцэст биш — ᠪᠠᠳᠮ᠎ᠠᠴᠡᠴᠡᠭ
 *      гэж бичвэл зайлуулагч буруу байрлалд орно.
 *   2. **ᠠᠠ давхарлана.** «сар»+«ан» мэт залгаа хоёр хэсэг эгшгээрээ
 *      мөргөлдвөл дунд нь ᠭ ордог (`long-vowel-aa` дүрэм).
 *
 *   3. **Дугуй эгшгийн шүд алга болно.** Хоёр дахь хэсгийн эхний ᠣ/ᠤ/ᠥ/ᠦ нь
 *      залгасны дараа үгийн эхний үед байхаа болих тул фонт түүнийг гэдэс
 *      дангаар нь зурна — `keepRoundedTooth` FVS1-ээр шүдийг нь барина.
 */
export function joinScript(parts: string[]): string {
  return parts.filter(Boolean).reduce((out, part) => {
    if (!out) return part;

    // Дундах зайлуулагчийг хасна — MVS зөвхөн үгийн эцэст утгатай.
    const mvsAt = out.length - 2;
    const head =
      out[mvsAt] === MVS ? out.slice(0, mvsAt) + out.slice(mvsAt + 1) : out;

    const last = head.slice(-1);
    const bridge = (last === "ᠠ" || last === "ᠡ") && part.startsWith(last) ? "ᠭ" : "";

    return head + bridge + keepRoundedTooth(part);
  }, "");
}

/**
 * НИЙЛМЭЛ ҮГИЙН ХОЁР ДАХЬ ХЭСГИЙН ДУГУЙ ЭГШГИЙГ ШҮДТЭЙ ХЭВЭЭР БАРИНА.
 *
 * «Амармөрөн» = «амар» (ᠠᠮᠤᠷ) + «мөрөн» (ᠮᠥᠷᠡᠨ). Хоёуланг нь зүгээр залгавал
 * ᠠᠮᠤᠷᠮᠥᠷᠡᠨ гарах ба ᠥ нь одоо үгийн эхний үед биш — фонт түүнийг «гэдэс»
 * дангаар нь зурж, «мөрөн» нь уншигдахаа болино. Кимо хөрвүүлэгч энэ
 * байрлалд FVS1 тавьдаг: ᠠᠮᠤᠷᠮᠥ᠋ᠷᠡᠨ.
 *
 * ⚠ ЗӨВХӨН ЭМ дугуй эгшигт (ᠥ ᠦ). Эр ᠣ/ᠤ нь дундаа ч шүдээ алддаггүй тул
 * заагт нь юу ч тавихгүй — кимо ᠪᠠᠲᠤᠵᠤᠯᠠ, ᠠᠯᠲᠠᠨᠲᠤᠶᠠᠭ᠎ᠠ, ᠭᠡᠷᠡᠯᠪᠣᠯᠤᠳ
 * гурвыг хэвээр үлдээж, ᠪᠠᠲᠤᠮᠥᠩᠬᠡ, ᠠᠯᠲᠠᠨᠲᠥᠪᠰᠢᠨ дээр л хувилбар тавив.
 *
 * ⚠ Энэ бол ЗӨВ БИЧИХ ЗҮЙН биш, ДҮРСЛЭЛИЙН дүрэм — тиймээс толиос хэмжиж
 * гаргах юм алга (Их тайлбар толь нийлмэл үгэндээ FVS огт тавьдаггүй, тэр ч
 * учраас түүний ᠪᠠᠳᠮᠠᠭᠣᠮᠪᠤ мэт бичлэгүүд дэлгэц дээр «-гумбу» шиг харагддаг).
 * Unicode-ийн монгол хэлбэрийн хүснэгтэд дундах ᠥ/ᠦ-гийн өгөгдмөл дүрс гэдэс
 * дангаараа, FVS1-тэй нь шүдтэй гэж заасан нь эх сурвалж.
 *
 * Хэсэг өөрөө эгшгээр эхэлж байвал (index 0) хөндөхгүй: тэнд анхнаасаа шүд
 * байгаагүй бөгөөд залгасны дараа сэргээх боломжгүй.
 */
function keepRoundedTooth(part: string): string {
  for (let index = 0; index < part.length; index += 1) {
    const char = part[index];
    if (!SCRIPT_VOWELS.has(char)) continue;

    if (index === 0 || !FRONT_ROUNDED_VOWELS.has(char)) return part;
    if (part[index + 1] === FVS1) return part;

    return part.slice(0, index + 1) + FVS1 + part.slice(index + 1);
  }

  return part;
}

function separateFinalVowel(script: string): string {
  const last = script.slice(-1);
  if (last !== "ᠠ" && last !== "ᠡ") return script;

  const previous = script.slice(-2, -1);
  if (!previous || previous === MVS) return script;
  if (!separatesFinalVowel(previous, last)) return script;

  return script.slice(0, -1) + MVS + last;
}

